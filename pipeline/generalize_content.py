from pathlib import Path

def process_file(filepath, replacements):
    p = Path(filepath)
    if not p.exists(): return
    txt = p.read_text(encoding="utf-8")
    for old, new in replacements:
        txt = txt.replace(old, new)
    p.write_text(txt, encoding="utf-8")


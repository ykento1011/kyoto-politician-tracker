#requires -Version 5.1
[CmdletBinding()]
param([string]$PlanPath,[string]$ExpectedPlanSha256,[string]$JournalRoot,
      [string]$ObservedRulesPath,[switch]$Apply,[switch]$SelfTest)
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
# No parameter enables live changes. Source activation needs a separate GO.
$script:LiveFirewallChangesEnabled=$false

function Get-RemovalNames {
    param($Plan,$Started,$Done,$Release,$Observed,[bool]$HoldExists,[string]$PlanSha,$Success,[string]$DoneSha)
    if($HoldExists){throw 'Persistent HOLD; do not restore automatically'}
    if(($Plan.schema_version -isnot [int] -and $Plan.schema_version -isnot [long]) -or $Plan.schema_version -ne 1 -or $Plan.run_id -isnot [string] -or $Plan.run_id -cnotmatch '^[0-9a-f]{32}$'){throw 'Invalid plan identity'}
    if($PlanSha -cnotmatch '^[0-9a-f]{64}$'){throw 'Invalid plan SHA'}
    foreach($record in @($Started,$Done,$Release,$Success)){
        if($record.run_id -cne $Plan.run_id -or $record.plan_sha256 -cne $PlanSha){throw 'Journal/plan mismatch'}
    }
    foreach($value in @($Started.auto_restore,$Done.auto_restore,$Done.termination_confirmed,$Done.cleanup_complete,$Release.all_processes_exited)){if($value -isnot [bool]){throw 'Boolean evidence required'}}
    if($Started.auto_restore -ne $false -or $Done.auto_restore -ne $false -or
       $Done.termination_confirmed -ne $true -or $Done.cleanup_complete -ne $true){throw 'Termination unconfirmed'}
    if($Done.elapsed_seconds -lt 0 -or $Done.elapsed_seconds -ge $Done.total_seconds){throw 'Deadline not satisfied'}
    # Human acknowledgement is an input, never generated by this script.
    if($Release.decision -cne 'manual_restore_after_local_exit_check' -or
       $Release.actor -cne 'onsite_operator' -or $Release.all_processes_exited -ne $true){throw 'Local recovery acknowledgement missing'}
    if($null -eq $Success -or $Success.completion_token -isnot [string] -or $Success.completion_token -cnotmatch '^[0-9a-f]{64}$'){throw 'Successful supervisor commit missing'}
    $algorithm=[Security.Cryptography.SHA256]::Create()
    try{$tokenHash=[BitConverter]::ToString($algorithm.ComputeHash([Text.Encoding]::UTF8.GetBytes($Success.completion_token))).Replace('-','').ToLowerInvariant()}finally{$algorithm.Dispose()}
    if($tokenHash -cne $Started.completion_token_sha256 -or $Success.termination_record_sha256 -cne $DoneSha -or
       $Success.elapsed_seconds -lt 0 -or $Success.elapsed_seconds -ge $Done.total_seconds){throw 'Supervisor capability or exact termination record mismatch'}
    $prefix='GikaiMikata-Stage2-'+$Plan.run_id
    if(@($Plan.added_rules).Count -ne 2){throw 'Exactly two planned delta rules required'}
    $names=@()
    foreach($direction in @('Inbound','Outbound')){
        $expectedName=$prefix+'-'+$direction
        $planned=@($Plan.added_rules | Where-Object {$_.name -ceq $expectedName})
        if($planned.Count -ne 1 -or $planned[0].direction -cne $direction){throw 'Foreign/duplicate planned rule'}
        $matches=@($Observed | Where-Object {$_.Name -ceq $expectedName})
        if($matches.Count -ne 1){throw 'Missing/duplicate observed rule; no broad fallback'}
        $r=$matches[0]
        if($r.Group -cne $prefix -or $r.Direction -cne $direction -or $r.Action -cne 'Block' -or
           $r.Enabled -cne 'True' -or $r.Profile -cne 'Any' -or $r.Program -cne 'Any' -or
           $r.Service -cne 'Any' -or $r.Protocol -cne 'Any' -or $r.LocalAddress -cne 'Any' -or
           $r.RemoteAddress -cne 'Any' -or $r.LocalPort -cne 'Any' -or $r.RemotePort -cne 'Any' -or
           $r.LocalUser -cne 'Any' -or $r.RemoteUser -cne 'Any' -or $r.OverrideBlockRules -cne 'False'){
            throw 'Observed rule differs from approved delta'
        }
        $names+=$expectedName
    }
    return $names
}

function Get-ExactLiveRule {
    param([string]$Name)
    $rule=@(Get-NetFirewallRule -PolicyStore ActiveStore -Name $Name -ErrorAction Stop)
    if($rule.Count -ne 1 -or $rule[0].PolicyStoreSourceType.ToString() -cne 'Local'){throw 'Exact local rule required'}
    $r=$rule[0];$a=$r|Get-NetFirewallApplicationFilter;$s=$r|Get-NetFirewallServiceFilter
    $p=$r|Get-NetFirewallPortFilter;$addr=$r|Get-NetFirewallAddressFilter;$security=$r|Get-NetFirewallSecurityFilter
    $alias=$r|Get-NetFirewallInterfaceFilter;$type=$r|Get-NetFirewallInterfaceTypeFilter
    if(($a.Package -and $a.Package -cne 'Any') -or (@($alias.InterfaceAlias) -join ',') -cne 'Any' -or
       $type.InterfaceType.ToString() -cnotin @('Any','0')){throw 'Unexpected interface or package filter'}
    return [pscustomobject]@{Name=$r.Name;Group=$r.Group;Direction=$r.Direction.ToString();Action=$r.Action.ToString();
        Enabled=$r.Enabled.ToString();Profile=$r.Profile.ToString();Program=$a.Program;Service=$s.Service;
        Protocol=$p.Protocol.ToString();LocalAddress=(@($addr.LocalAddress)-join ',');RemoteAddress=(@($addr.RemoteAddress)-join ',');
        LocalPort=(@($p.LocalPort)-join ',');RemotePort=(@($p.RemotePort)-join ',');LocalUser=$security.LocalUser;
        RemoteUser=$security.RemoteUser;OverrideBlockRules=$r.OverrideBlockRules.ToString()}
}
function Remove-ExactLiveDelta {
    param([string[]]$Names,$Expected)
    if(-not $script:LiveFirewallChangesEnabled){throw 'Live removal disabled'}
    foreach($name in $Names){
        $now=Get-ExactLiveRule $name
        $prior=@($Expected|Where-Object {$_.Name -ceq $name})
        if($prior.Count -ne 1 -or ($now|ConvertTo-Json -Compress) -cne ($prior[0]|ConvertTo-Json -Compress)){throw 'Rule changed before removal'}
        # Explicit names only, no wildcard/group/whole-policy fallback.
        Remove-NetFirewallRule -PolicyStore PersistentStore -Name $name -Confirm:$false -ErrorAction Stop
        if(@(Get-NetFirewallRule -PolicyStore ActiveStore -Name $name -ErrorAction SilentlyContinue).Count -ne 0){throw 'Rule removal unconfirmed'}
    }
}
function Assert-PrivateInput {
    param([string]$Path,[string]$Root)
    $full=[IO.Path]::GetFullPath($Path)
    $base=[IO.Path]::GetFullPath($Root).TrimEnd('\')
    if($full -notmatch '^[A-Za-z]:\\' -or ($full -cne $base -and -not $full.StartsWith($base+'\',[StringComparison]::OrdinalIgnoreCase))){throw 'Local private journal input required'}
    $actor=[System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value
    $cursor=$full
    while($true){
        $item=Get-Item -LiteralPath $cursor -Force -ErrorAction Stop
        if(($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0){throw 'Reparse input refused'}
        $acl=Get-Acl -LiteralPath $cursor
        if($acl.GetOwner([System.Security.Principal.SecurityIdentifier]).Value -cne $actor){throw 'Journal owner mismatch'}
        $bad=@($acl.GetAccessRules($true,$true,[System.Security.Principal.SecurityIdentifier])|Where-Object {$_.AccessControlType -eq 'Allow' -and $_.IdentityReference.Value -cne $actor})
        if($bad.Count -ne 0){throw 'Owner-only journal input required'}
        if($cursor -eq $base){break}
        $cursor=[IO.Path]::GetDirectoryName($cursor)
    }
    return $full
}
function Initialize-DirectoryLocks {
    if('Stage2ReadOnly.DirectoryLock' -as [type]){throw 'Unexpected preloaded directory-lock type'}
    Add-Type -TypeDefinition @"
using System;
using System.IO;
using System.Text;
using System.Runtime.InteropServices;
using Microsoft.Win32.SafeHandles;
namespace Stage2ReadOnly {
 public static class DirectoryLock {
  [StructLayout(LayoutKind.Sequential)] struct FT { public uint Low,High; }
  [StructLayout(LayoutKind.Sequential)] struct Info { public uint Attributes; public FT Created,Accessed,Written; public uint Volume,SizeHigh,SizeLow,Links,IndexHigh,IndexLow; }
  [DllImport("kernel32.dll",CharSet=CharSet.Unicode,SetLastError=true)] static extern SafeFileHandle CreateFileW(string path,uint access,uint share,IntPtr security,uint disposition,uint flags,IntPtr template);
  [DllImport("kernel32.dll",SetLastError=true)] static extern bool GetFileInformationByHandle(SafeFileHandle handle,out Info info);
  [DllImport("kernel32.dll",CharSet=CharSet.Unicode,SetLastError=true)] static extern uint GetFinalPathNameByHandleW(SafeFileHandle handle,StringBuilder path,uint capacity,uint flags);
  public static SafeFileHandle Open(string path) {
   SafeFileHandle h=CreateFileW(path,0x20080,3,IntPtr.Zero,3,0x02200000,IntPtr.Zero);
   if(h.IsInvalid){h.Dispose();throw new IOException("Cannot lock directory");}
   try {
    Info info;if(!GetFileInformationByHandle(h,out info)||(info.Attributes&0x400)!=0||(info.Attributes&0x10)==0)throw new IOException("Unsafe directory identity");
    StringBuilder b=new StringBuilder(32768);uint n=GetFinalPathNameByHandleW(h,b,32768,0);
    if(n==0||n>=32768)throw new IOException("Directory path query failed");
    string actual=b.ToString();if(actual.StartsWith(@"\\?\",StringComparison.Ordinal))actual=actual.Substring(4);
    if(!String.Equals(actual.TrimEnd('\\'),Path.GetFullPath(path).TrimEnd('\\'),StringComparison.OrdinalIgnoreCase))throw new IOException("Directory alias or replacement");
    return h;
   } catch {h.Dispose();throw;}
  }
 }
}
"@
}
function Get-StreamSha {
    param([IO.Stream]$Stream)
    $Stream.Position=0;$sha=[Security.Cryptography.SHA256]::Create()
    try{return [BitConverter]::ToString($sha.ComputeHash($Stream)).Replace('-','').ToLowerInvariant()}finally{$sha.Dispose();$Stream.Position=0}
}
function Read-JsonStream {
    param([IO.Stream]$Stream)
    if($Stream.Length -gt 1048576){throw 'Bounded journal input required'}
    $Stream.Position=0;$reader=[IO.StreamReader]::new($Stream,[Text.Encoding]::UTF8,$true,4096,$true)
    try{return $reader.ReadToEnd()|ConvertFrom-Json}finally{$reader.Dispose();$Stream.Position=0}
}
function Read-JsonFile {param([string]$Path) Get-Content -LiteralPath $Path -Raw | ConvertFrom-Json}

if($SelfTest){
    Initialize-DirectoryLocks
    $stream=[IO.MemoryStream]::new([Text.Encoding]::UTF8.GetBytes('{"synthetic":true}'))
    try{if((Read-JsonStream $stream).synthetic -ne $true -or (Get-StreamSha $stream).Length -ne 64){throw 'Held stream verification failed'}}finally{$stream.Dispose()}
    function Get-NetFirewallRule { throw 'Real Firewall read forbidden in SelfTest' }
    function Remove-NetFirewallRule { throw 'Real Firewall mutation forbidden in SelfTest' }
    $id='a'*32;$sha='b'*64;$prefix='GikaiMikata-Stage2-'+$id
    $plan=[pscustomobject]@{schema_version=1;run_id=$id;added_rules=@(
        [pscustomobject]@{name=$prefix+'-Inbound';direction='Inbound'},
        [pscustomobject]@{name=$prefix+'-Outbound';direction='Outbound'})}
    $started=[pscustomobject]@{run_id=$id;plan_sha256=$sha;auto_restore=$false}
    $done=[pscustomobject]@{run_id=$id;plan_sha256=$sha;auto_restore=$false;termination_confirmed=$true;cleanup_complete=$true;elapsed_seconds=1;total_seconds=10}
    $release=[pscustomobject]@{run_id=$id;plan_sha256=$sha;decision='manual_restore_after_local_exit_check';actor='onsite_operator';all_processes_exited=$true}
    $token='e'*64;$digest=[Security.Cryptography.SHA256]::Create()
    try{$started|Add-Member completion_token_sha256 ([BitConverter]::ToString($digest.ComputeHash([Text.Encoding]::UTF8.GetBytes($token))).Replace('-','').ToLowerInvariant())}finally{$digest.Dispose()}
    $doneSha='d'*64
    $success=[pscustomobject]@{run_id=$id;plan_sha256=$sha;completion_token=$token;termination_record_sha256=$doneSha;elapsed_seconds=1}
    $rows=@(foreach($d in @('Inbound','Outbound')){[pscustomobject]@{Name=$prefix+'-'+$d;Group=$prefix;Direction=$d;Action='Block';Enabled='True';Profile='Any';Program='Any';Service='Any';Protocol='Any';LocalAddress='Any';RemoteAddress='Any';LocalPort='Any';RemotePort='Any';LocalUser='Any';RemoteUser='Any';OverrideBlockRules='False'}})
    if(@(Get-RemovalNames $plan $started $done $release $rows $false $sha $success $doneSha).Count -ne 2){throw 'Positive test failed'}
    $passed=3
    foreach($case in @('hold','unconfirmed','foreign','duplicate','elapsed','no_ack','different_sha','changed_rule','missing_program','string_boolean','bad_success','bad_done_sha','missing_success')){
        $p=$plan|ConvertTo-Json -Depth 10|ConvertFrom-Json;$s=$started|ConvertTo-Json|ConvertFrom-Json;$d=$done|ConvertTo-Json|ConvertFrom-Json;$a=$release|ConvertTo-Json|ConvertFrom-Json;$c=$success|ConvertTo-Json|ConvertFrom-Json
        # PS5.1 emits a JSON array as one array object; clone each row instead.
        $o=@(foreach($row in $rows){ConvertFrom-Json -InputObject (ConvertTo-Json -InputObject $row -Depth 10)})
        if($o.Count -ne $rows.Count){throw 'Synthetic row count changed'}
        foreach($row in $o){if($row -isnot [pscustomobject] -or $null -eq $row.PSObject.Properties['Program']){throw 'Synthetic row shape changed'}}
        switch($case){'unconfirmed'{$d.termination_confirmed=$false};'foreign'{$p.added_rules[0].name='foreign'};'duplicate'{$o+= $o[0]};'elapsed'{$d.elapsed_seconds=10};'no_ack'{$a.all_processes_exited=$false};'different_sha'{$s.plan_sha256='c'*64};'changed_rule'{$o[0].Program='other.exe'};'missing_program'{$o[0].PSObject.Properties.Remove('Program')};'string_boolean'{$d.termination_confirmed='True'};'bad_success'{$c.completion_token='f'*64};'bad_done_sha'{$c.termination_record_sha256='f'*64};'missing_success'{$c=$null}}
        $blocked=$false
        try{$null=Get-RemovalNames $p $s $d $a $o ($case -eq 'hold') $sha $c $doneSha}catch{$blocked=$true}
        if(-not $blocked){throw ('Negative test failed: '+$case)}
        $passed++
    }
    @{mode='synthetic_only';passed=$passed;firewall_reads=0;firewall_writes=0}|ConvertTo-Json -Compress
    return
}
if(-not $PlanPath -or -not $ExpectedPlanSha256 -or -not $JournalRoot){throw 'Fixed plan SHA and journal required'}
if($Apply){throw 'Live Firewall changes disabled; separate Stage 2 GO required'}
if(-not $Apply -and -not $ObservedRulesPath){throw 'Dry-run requires a synthetic/saved observed-rules file; no live enumeration'}
$locks=@();$directoryLocks=@();$streams=@{}
try {
$rootFull=[IO.Path]::GetFullPath($JournalRoot)
if($rootFull -notmatch '^[A-Za-z]:\\'){throw 'Local journal root required'}
Initialize-DirectoryLocks
$ancestors=@();$cursor=[IO.DirectoryInfo]::new($rootFull)
while($null -ne $cursor){$ancestors=@($cursor.FullName)+$ancestors;$cursor=$cursor.Parent}
foreach($ancestor in $ancestors){$directoryLocks+=[Stage2ReadOnly.DirectoryLock]::Open($ancestor)}
$inputs=@($PlanPath,(Join-Path $JournalRoot 'run_started.json'),(Join-Path $JournalRoot 'termination_confirmed.json'),(Join-Path $JournalRoot 'supervisor_success.json'),(Join-Path $JournalRoot 'operator_release.json'))
if(-not $Apply){$inputs+=$ObservedRulesPath}
foreach($inputFile in $inputs){
    $full=Assert-PrivateInput $inputFile $JournalRoot
    $stream=[IO.File]::Open($full,[IO.FileMode]::Open,[IO.FileAccess]::Read,[IO.FileShare]::Read)
    $locks+=$stream;$streams[$full]=$stream
}
$actual=Get-StreamSha $streams[[IO.Path]::GetFullPath($PlanPath)]
if($actual -cne $ExpectedPlanSha256){throw 'Plan byte SHA mismatch'}
$plan=Read-JsonStream $streams[[IO.Path]::GetFullPath($PlanPath)]
if($Apply -and @($plan.PSObject.Properties.Name) -contains 'synthetic'){throw 'Synthetic plans can never be applied'}
$started=Read-JsonStream $streams[[IO.Path]::GetFullPath((Join-Path $JournalRoot 'run_started.json'))]
$doneStream=$streams[[IO.Path]::GetFullPath((Join-Path $JournalRoot 'termination_confirmed.json'))]
$done=Read-JsonStream $doneStream;$doneSha=Get-StreamSha $doneStream
$success=Read-JsonStream $streams[[IO.Path]::GetFullPath((Join-Path $JournalRoot 'supervisor_success.json'))]
$release=Read-JsonStream $streams[[IO.Path]::GetFullPath((Join-Path $JournalRoot 'operator_release.json'))]
if($Apply){$observed=@(foreach($r in $plan.added_rules){Get-ExactLiveRule $r.name})}else{$observed=@(Read-JsonStream $streams[[IO.Path]::GetFullPath($ObservedRulesPath)])}
$names=@(Get-RemovalNames $plan $started $done $release $observed (Test-Path -LiteralPath (Join-Path $JournalRoot 'HOLD.json')) $actual $success $doneSha)
if($Apply){Remove-ExactLiveDelta $names $observed}
@{mode=($(if($Apply){'manual_delta_removed'}else{'dry_run'}));would_remove=$names;firewall_writes=($(if($Apply){$names.Count}else{0}));automatic_restore=$false}|ConvertTo-Json -Depth 4
} finally {
    foreach($stream in $locks){$stream.Dispose()}
    for($i=$directoryLocks.Count-1;$i -ge 0;$i--){$directoryLocks[$i].Dispose()}
}
